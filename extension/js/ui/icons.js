/**
 * Returns a Lucide weather SVG string for a WMO code, icon key, or legacy weather emoji.
 * @param {number | string | null | undefined} codeOrIcon
 * @param {number} [size=28]
 * @returns {string}
 */
export function getWeatherIconSvg(codeOrIcon, size = 28) {
  let key = 'cloud-sun';
  if (typeof codeOrIcon === 'number') {
    if (codeOrIcon === 0) key = 'sun';
    else if (codeOrIcon === 1 || codeOrIcon === 2) key = 'cloud-sun';
    else if (codeOrIcon === 3) key = 'cloud';
    else if (codeOrIcon === 45 || codeOrIcon === 48) key = 'cloud-fog';
    else if (codeOrIcon >= 51 && codeOrIcon <= 57) key = 'cloud-drizzle';
    else if ((codeOrIcon >= 61 && codeOrIcon <= 67) || (codeOrIcon >= 80 && codeOrIcon <= 82)) key = 'cloud-rain';
    else if ((codeOrIcon >= 71 && codeOrIcon <= 77) || codeOrIcon === 85 || codeOrIcon === 86) key = 'cloud-snow';
    else if (codeOrIcon >= 95) key = 'cloud-lightning';
  } else if (typeof codeOrIcon === 'string') {
    const trimmed = codeOrIcon.trim();
    if (WEATHER_ICON_PATHS[trimmed]) key = trimmed;
    else if (WEATHER_EMOJI_MAP[trimmed]) key = WEATHER_EMOJI_MAP[trimmed];
  }
  const paths = WEATHER_ICON_PATHS[key] || WEATHER_ICON_PATHS['cloud-sun'];
  return `<svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" class="svg-icon weather-lucide-icon lucide-${key}" aria-hidden="true">${paths}</svg>`;
}
