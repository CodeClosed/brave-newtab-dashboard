/**
 * Resolves any icon key or legacy emoji to a valid Lucide icon key.
 * @param {string | null | undefined} keyOrEmoji
 * @param {string} [fallback='folder']
 * @returns {string}
 */
export function resolveIconKey(keyOrEmoji, fallback = 'folder') {
  if (!keyOrEmoji || typeof keyOrEmoji !== 'string') return fallback;
  const trimmed = keyOrEmoji.trim();
  if (LUCIDE_ICON_PATHS[trimmed]) return trimmed;
  if (LEGACY_EMOJI_TO_LUCIDE[trimmed]) return LEGACY_EMOJI_TO_LUCIDE[trimmed];
  const lower = trimmed.toLowerCase();
  if (LUCIDE_ICON_PATHS[lower]) return lower;
  if (LEGACY_EMOJI_TO_LUCIDE[lower]) return LEGACY_EMOJI_TO_LUCIDE[lower];
  return fallback;
}

/**
 * Renders a Lucide SVG string for any icon key or legacy emoji.
 * Never outputs raw emoji characters.
 *
 * @param {string | null | undefined} keyOrEmoji
 * @param {number} [size=15]
 * @param {string} [extraClass='']
 * @returns {string}
 */
export function getIconSvg(keyOrEmoji, size = 15, extraClass = '') {
  const key = resolveIconKey(keyOrEmoji, 'folder');
  const paths = LUCIDE_ICON_PATHS[key] || LUCIDE_ICON_PATHS.folder;
  const cls = ['svg-icon', `lucide-${key}`, extraClass].filter(Boolean).join(' ');
  return `<svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="${cls}" aria-hidden="true">${paths}</svg>`;
}

